"use client";
// The printable decision letter for one scored applicant (ROADMAP 6.3.6).
// Rendered on the Score page but only visible on paper (`print-only`); built
// from the live result, so it always matches what is on screen.
import { pct, money } from "@/lib/api";
import { CATEGORY_LABELS, featureLabel } from "@/lib/labels";

const SUMMARY = [
  ["fico", (v) => v],
  ["dti", (v) => `${v}%`],
  ["ltv", (v) => `${v}%`],
  ["orig_interest_rate", (v) => `${v}%`],
  ["orig_upb", (v) => money(v)],
  ["orig_loan_term", (v) => `${v / 12} years`],
  ["occupancy_status", (v) => CATEGORY_LABELS.occupancy_status[v] ?? v],
  ["loan_purpose", (v) => CATEGORY_LABELS.loan_purpose[v] ?? v],
  ["property_type", (v) => CATEGORY_LABELS.property_type[v] ?? v],
  ["first_time_homebuyer", (v) => CATEGORY_LABELS.first_time_homebuyer[v] ?? v],
];

export default function DecisionLetter({ res, form, whatif }) {
  const approved = res.decision === "approve";
  const reasons = res.reason_codes || [];
  const options = whatif?.options || [];
  const date = new Date().toLocaleDateString(undefined, { dateStyle: "long" });

  return (
    <article className="print-only letter" aria-hidden="true">
      <header className="letter-head">
        <div className="print-brand">CreditCast</div>
        <div className="letter-meta">
          <div>{date}</div>
          {res.request_id && <div>Reference {res.request_id}</div>}
          {res.model_fingerprint && <div>Model {res.model_fingerprint}</div>}
        </div>
      </header>

      <h1>Mortgage application — {approved ? "approved" : "not approved"}</h1>

      <p>
        {approved
          ? "Based on the information provided, this mortgage application meets our approval criteria."
          : "Based on the information provided, we are unable to approve this mortgage application at this time. The principal reasons are set out below."}
      </p>

      <h2>Application summary</h2>
      <table className="letter-table">
        <tbody>
          {SUMMARY.map(([k, fmt]) => (
            <tr key={k}><th scope="row">{featureLabel(k)}</th><td>{fmt(form[k])}</td></tr>
          ))}
        </tbody>
      </table>

      <h2>Assessment</h2>
      <table className="letter-table">
        <tbody>
          <tr><th scope="row">Decision</th><td><strong>{approved ? "Approved" : "Declined"}</strong></td></tr>
          <tr><th scope="row">Estimated probability of default (12 months)</th>
            <td>{pct(res.pd)} (approval limit {pct(res.threshold)})</td></tr>
          <tr><th scope="row">Risk grade</th><td>{res.risk_band} (scale AAA lowest risk → B highest)</td></tr>
          <tr><th scope="row">Expected loss</th><td>{money(res.expected_loss)}</td></tr>
        </tbody>
      </table>

      {!approved && (
        <>
          <h2>Principal reasons</h2>
          {reasons.length ? (
            <ol>{reasons.map((r) => <li key={r.rank}>{r.reason}</li>)}</ol>
          ) : (
            <p>The estimated probability of default is above the approval limit.</p>
          )}
          {options.length > 0 && (
            <>
              <h2>What could change the outcome</h2>
              <p>Any one of the following changes alone would bring the application within the approval limit:</p>
              <ul>{options.map((o) => <li key={o.feature}>{o.text}.</li>)}</ul>
            </>
          )}
        </>
      )}

      <footer className="letter-foot">
        This letter was generated by CreditCast, a demonstration credit-risk system trained on synthetic
        mortgage data. It is not an offer or refusal of credit from any lender.
      </footer>
    </article>
  );
}
